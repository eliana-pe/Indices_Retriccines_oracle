-- 16. Consulta de archivos Redo y modo ARCHIVELOG/NOARCHIVELOG

SELECT
    d.LOG_MODE AS MODO,
    l.GROUP# AS GRUPO,
    l.SEQUENCE# AS SECUENCIA,
    ROUND(l.BYTES / 1024 / 1024, 2) AS TAMANO_MB,
    l.STATUS AS ESTADO,
    f.MEMBER AS ARCHIVO_REDO
FROM V$DATABASE d
CROSS JOIN V$LOG l
JOIN V$LOGFILE f
    ON l.GROUP# = f.GROUP#
WHERE f.TYPE = 'ONLINE'
ORDER BY l.GROUP#;