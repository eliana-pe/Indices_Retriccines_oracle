-- 2. Consulta de índices de EMPLOYEES y DEPARTMENTS

SELECT
    i.table_name AS TABLA,
    i.index_name AS INDICE,
    c.column_name AS COLUMNA,
    c.column_position AS POSICION,
    i.uniqueness AS UNICIDAD,
    i.index_type AS TIPO,
    i.status AS ESTADO
FROM user_indexes i
JOIN user_ind_columns c
    ON i.index_name = c.index_name
    AND i.table_name = c.table_name
WHERE i.table_name IN ('EMPLOYEES', 'DEPARTMENTS')
ORDER BY i.table_name, i.index_name, c.column_position;


-- 3. Consulta de restricciones de EMPLOYEES y DEPARTMENTS

SELECT
    c.table_name AS TABLA,
    c.constraint_name AS RESTRICCION,
    c.constraint_type AS TIPO,
    cc.column_name AS COLUMNA,
    c.status AS ESTADO,
    c.validated AS VALIDACION
FROM user_constraints c
LEFT JOIN user_cons_columns cc
    ON c.constraint_name = cc.constraint_name
    AND c.table_name = cc.table_name
WHERE c.table_name IN ('EMPLOYEES', 'DEPARTMENTS')
ORDER BY c.table_name, c.constraint_name, cc.position;


-- 4. Consulta de dependencias entre restricciones

SELECT
    p.table_name AS TABLA_REFERENCIADA,
    p.constraint_name AS RESTRICCION_REFERENCIADA,
    h.table_name AS TABLA_DEPENDIENTE,
    h.constraint_name AS CLAVE_FORANEA,
    h.status AS ESTADO
FROM user_constraints p
JOIN user_constraints h
    ON h.r_constraint_name = p.constraint_name
    AND h.r_owner = USER
WHERE p.table_name IN ('EMPLOYEES', 'DEPARTMENTS')
    AND h.constraint_type = 'R'
ORDER BY p.table_name, h.table_name, h.constraint_name;


